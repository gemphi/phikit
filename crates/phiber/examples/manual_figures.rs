//! Draws the manual's figures — one SVG per distinct screen, all in the
//! same deck.
//!
//! The figure is not a screenshot and not a hand drawing. It is generated
//! from the same declarative sets that build the app: the screen's regions
//! come from `BHostType::spec().regions` and its toolbars and sidebars from
//! those regions' panes, so a figure cannot drift from the editor it
//! depicts — add a region to a host and its figure grows one the next time
//! this runs. That is the whole reason the manual is declared
//! (`v2::manual`) rather than written as loose files.
//!
//! Run with:  cargo run --release -p phiber --example manual_figures
//! Writes to: crates/phiber/docs/manual/figures/<space>-<host>.svg

use phiber::v2::manual::{BDeck, figures};
use phiber::v2::pane::BPaneType;
use phiber::v2::region::BRegionType;
use phiber::v2::theme::{BColor, BThemeMode, palette_in};

const W: f32 = 760.0;
const H: f32 = 470.0;
/// Room under the cascade for the caption.
const CAPTION: f32 = 26.0;

fn hex(c: BColor) -> String {
    // The palette stores HSL in degrees/percent; SVG wants sRGB bytes.
    let (h, s, l) = (c.0 / 360.0, c.1 / 100.0, c.2 / 100.0);
    let f = |n: f32| {
        let k = (n + h * 12.0) % 12.0;
        let a = s * l.min(1.0 - l);
        let v = l - a * (-1.0f32).max((k - 3.0).min(9.0 - k).min(1.0));
        (v.clamp(0.0, 1.0) * 255.0 + 0.5) as u8
    };
    format!("#{:02x}{:02x}{:02x}", f(0.0), f(8.0), f(4.0))
}

/// A colour `step` points lighter — how the cascade separates its panels
/// and how a region lifts off the panel it sits on. The ladder's own step
/// is a lightness delta, so this is the same move the editor makes.
fn lift(c: BColor, step: f32) -> BColor {
    (c.0, c.1, (c.2 + step).clamp(0.0, 100.0), c.3)
}

/// Where a region sits inside the screen, as shares of it — the four edges
/// Blender's regions take (`ARegion.alignment`). `Center` is what is left.
fn slot(kind: BRegionType) -> Option<(f32, f32, f32, f32)> {
    Some(match kind {
        BRegionType::ToolHeader => (0.00, 0.000, 1.00, 0.065),
        BRegionType::Header => (0.00, 0.065, 1.00, 0.080),
        BRegionType::NavBar => (0.00, 0.145, 0.070, 0.740),
        BRegionType::Channels => (0.00, 0.145, 0.200, 0.740),
        BRegionType::Center => (0.00, 0.145, 1.00, 0.740),
        BRegionType::Scrubbing => (0.00, 0.145, 1.00, 0.050),
        BRegionType::AssetShelfHeader => (0.00, 0.845, 1.00, 0.040),
        BRegionType::AssetShelf => (0.00, 0.885, 1.00, 0.115),
        BRegionType::Footer => (0.00, 0.885, 1.00, 0.115),
        _ => return None,
    })
}

/// A pane's share of the region it is in. phiber floats the Toolbar and the
/// Sidebar over the canvas as the Left and Right panes of the Center region
/// rather than giving them regions of their own, so a figure that drew only
/// regions showed an editor with no tools down its side.
fn pane(kind: BPaneType) -> (f32, f32, f32, f32) {
    match kind {
        BPaneType::Left => (0.015, 0.04, 0.060, 0.92),
        BPaneType::Center => (0.000, 0.00, 1.000, 1.00),
        BPaneType::Right => (0.790, 0.04, 0.195, 0.92),
    }
}

fn rect(x: f32, y: f32, w: f32, h: f32, fill: &str, stroke: &str, r: f32) -> String {
    format!("<rect x=\"{x:.1}\" y=\"{y:.1}\" width=\"{w:.1}\" height=\"{h:.1}\" rx=\"{r}\" fill=\"{fill}\" stroke=\"{stroke}\" stroke-width=\"0.75\"/>\n")
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let deck = BDeck::SILVER;
    let p = palette_in(deck.palette, BThemeMode::Dark);
    let out = std::path::Path::new("crates/phiber/docs/manual/figures");
    std::fs::create_dir_all(out)?;
    let edge = hex(lift(p.bg_app, -3.0));

    let mut index = String::from("# Manual figures\n\nOne per screen, in the deck (`v2::manual::deck`). Generated by\n`examples/manual_figures.rs` from each host's own region and pane specs —\ndo not edit by hand.\n\n");
    let all = figures();
    for (figure, pages) in &all {
        let label = format!("{} · {}", figure.space.slug(), figure.host.spec().label);
        let mut svg = format!(
            r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="{label}">
<rect width="{W}" height="{H}" fill="{}"/>
"#,
            hex(p.bg_app)
        );

        // The deck: every layer centred, each one behind reaching a bar
        // further out top and bottom, so the steps read as a hexagon.
        let origin = (W * 0.035, H * 0.035);
        let span = (W - origin.0 * 2.0, H - origin.1 * 2.0 - CAPTION);
        let mut front = (0.0, 0.0, 0.0, 0.0);
        for (i, (dx, dy, w, h)) in deck.layers().iter().enumerate() {
            let (x, y) = (origin.0 + dx * span.0, origin.1 + dy * span.1);
            let (pw, ph) = (span.0 * w, span.1 * h);
            // Each layer back is one step of the editor's own ladder
            // lighter, so depth in the picture is depth on the screen.
            let shade = lift(p.bg_panel, f32::from(deck.shade(i)) * 4.5);
            svg += &rect(x, y, pw, ph, &hex(shade), &edge, 6.0);
            if i == deck.layers().len() - 1 {
                front = (x, y, pw, ph);
            }
        }

        // The front panel is the screen: its regions, from the host's own
        // spec, so this picture is the declaration drawn.
        let (fx, fy, fw, fh) = front;
        for region in figure.host.spec().regions {
            let Some((rx, ry, rw, rh)) = slot(region.kind) else { continue };
            let fill = match region.kind {
                BRegionType::Center => p.bg_viewport,
                BRegionType::Header | BRegionType::ToolHeader | BRegionType::Footer => lift(p.bg_header, 3.0),
                _ => lift(p.bg_panel, 6.0),
            };
            let (x, y, w, h) = (fx + rx * fw, fy + ry * fh, rw * fw, rh * fh);
            svg += &rect(x, y, w, h, &hex(fill), &edge, 3.0);
            if region.kind != BRegionType::Center {
                continue;
            }
            // and the Center region's own panes — the floating Toolbar and
            // Sidebar, which are panes here and not regions.
            for spec in region.panes {
                if spec.kind == BPaneType::Center || spec.parts.is_empty() {
                    continue;
                }
                let (px_, py, pw, ph) = pane(spec.kind);
                svg += &rect(x + px_ * w, y + py * h, pw * w, ph * h, &hex(lift(p.bg_panel, 9.0)), &edge, 3.0);
            }
        }

        svg += &format!(
            "<text x=\"{:.1}\" y=\"{:.1}\" font-family=\"system-ui,sans-serif\" font-size=\"13\" fill=\"{}\">{label}</text>\n</svg>\n",
            fx,
            (fy + fh + 19.0).min(H - 7.0),
            hex(p.text)
        );

        let name = format!("{}-{}.svg", figure.space.slug(), figure.host.spec().label.to_lowercase().replace(' ', "-"));
        std::fs::write(out.join(&name), svg)?;
        index += &format!("- `{name}` — {} page(s): {}\n", pages.len(), pages.iter().map(|n| n.slug).collect::<Vec<_>>().join(", "));
    }
    std::fs::write(out.join("README.md"), index)?;
    println!("wrote {} figures to {}", all.len(), out.display());
    Ok(())
}
