//! | `COLOR`, `COLOR_GAMMA` | `RGBA` |
//! | anything else | none -- the property takes no letter at all |
//!
//! An empty letter set means the property is not an array, so the format
//! string concatenates nothing, which is Blender's `arrayname = ""`.

