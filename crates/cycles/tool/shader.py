"""Write data/shader.tsv from Cycles' own source, so no node's traits are typed in.

  python tool/shader.py <path to intern/cycles>

Run after tool/node.py: the node types of each C++ class are read from
data/node.tsv. Reads scene/shader_nodes.h and shader_nodes.cpp:

  special   the `special_type` a node's constructor, or that of a class it
            derives from, gives it
  flag      a yes-or-no question of `ShaderNode` a class answers for itself:
            `true` or `false` when the header says so outright, `code` when
            the answer is worked out
  override  a function of `ShaderNode` a class has its own version of

A class takes what the nearest class above it says. `ConvertNode`'s special
type depends on how it is made, so it has no row.
"""
import io
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from value import read, strip_comment  # noqa: E402

CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FLAG = ['has_surface_emission', 'has_surface_transparent', 'has_surface_bssrdf', 'has_bump', 'has_bssrdf_bump',
        'has_spatial_varying', 'has_attribute_dependency', 'has_volume_support', 'is_linear_operation']
OVERRIDE = ['expand', 'constant_fold', 'simplify_settings', 'attributes', 'get_feature', 'get_closure_type', 'equals']


def class_list(header):
    """name -> (base, body) for each class of the header."""
    out = {}
    for found in re.finditer(r'^class (\w+)(?: : public (\w+))? \{(.*?)^\};', header, flags=re.S | re.M):
        out[found.group(1)] = (found.group(2) or '', found.group(3))
    return out


def own(name, body, source):
    """What a class says for itself: its special type, flags and overrides."""
    special = re.search(r'\b' + name + r'::' + name + r'\([^)]*\)[^{]*\{(.*?)\n\}', source, flags=re.S)
    special = re.search(r'special_type = (\w+);', (special.group(1) if special else '') + body)
    flag = {}
    for method in FLAG:
        inline = re.search(r'\bbool ' + method + r'\(\)(?: const)? override\s*\{\s*return ([^;]+);', body)
        declared = re.search(r'\bbool ' + method + r'\(\)(?: const)? override', body)
        if inline and inline.group(1).strip() in ('true', 'false'):
            flag[method] = inline.group(1).strip()
        elif declared:
            flag[method] = 'code'
    override = [method for method in OVERRIDE if re.search(r'\b' + method + r'\([^)]*\)(?: const)? override', body)]
    return (special.group(1) if special else '', flag, override)


def main():
    header = strip_comment(read(CYCLES, 'scene/shader_nodes.h'))
    source = strip_comment(read(CYCLES, 'scene/shader_nodes.cpp'))
    classes = class_list(header)
    said = {name: own(name, body, source) for name, (_, body) in classes.items()}
    node = {}
    for line in io.open(os.path.join(HERE, 'data', 'node.tsv'), encoding='utf-8'):
        cell = line.rstrip('\n').split('\t')
        if cell[0] == 'class' and cell[2] in classes:
            node.setdefault(cell[2], []).append(cell[1])
    rows = []
    for name in classes:
        chain = [name]
        while classes.get(chain[-1], ('', ''))[0] in classes:
            chain.append(classes[chain[-1]][0])
        special = next((said[item][0] for item in chain if said[item][0]), '')
        flag = {}
        for item in reversed(chain):
            flag.update(said[item][1])
        override = sorted({method for item in chain for method in said[item][2]}, key=OVERRIDE.index)
        for kind in node.get(name, []):
            if special and name != 'ConvertNode':
                rows.append(('special', kind, special))
            rows.extend(('flag', kind, method, flag[method]) for method in FLAG if flag.get(method, 'false') != 'false')
            rows.extend(('override', kind, method) for method in override)
    head = [
        '# Generated by tool/shader.py from Cycles: scene/shader_nodes.h and',
        '# shader_nodes.cpp. Do not edit by hand. What a shader node says of',
        '# itself, its own or taken from the class it derives from.',
        '#',
        '# special	node	the special type its constructor gives it',
        '# flag	node	question	true, or code when the answer is worked out',
        '# override	node	function it has its own version of',
    ]
    out = os.path.join(HERE, 'data', 'shader.tsv')
    with open(out, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(head + ['\t'.join(row) for row in rows]) + '\n')
    count = {kind: sum(1 for row in rows if row[0] == kind) for kind in ('special', 'flag', 'override')}
    print(out, count)


main()
