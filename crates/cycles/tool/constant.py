"""Write data/constant.tsv from Cycles' own source, so no flag is typed in.

  python tool/constant.py <path to intern/cycles>

Reads kernel/types.h and kernel/features.h: every enumerator of every enum,
and every `#define` that stands for a number. The kernel's flags and limits are looked up in
the table by the name Cycles gives them.

A manager's own update flags (scene/object.h, scene/geometry.h) are in an
enum with no name inside its class, and two managers use one name for
different bits, so those are written with the class: `ObjectManager::UPDATE_ALL`.

The BVH's own (bvh/params.h, bvh/binning.h, bvh/bvh.h, bvh/bvh2.h): the
enumerators of `BVHType`, the limits a class keeps in an enum with no name,
written with the class (`BVHParams::MAX_DEPTH`), and the sizes of a node.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from value import Names, read, show, strip_comment  # noqa: E402

CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def socket_flag(names):
    """`SocketType::Flags` of graph/node_type.h, written with the class: `SocketType::LINKABLE`."""
    text = strip_comment(read(CYCLES, 'graph/node_type.h'))
    body = re.search(r'enum Flags\s*\{(.*?)\}', text, flags=re.S).group(1)
    name = [item.partition('=')[0].strip() for item in body.split(',') if item.strip()]
    return [('SocketType', 'SocketType::' + item, show(names.scoped.get(('SocketType', item)))) for item in name]


def manager_flag(names):
    """The update flags of the object and geometry managers, and the device update flags."""
    rows = []
    for path in ('scene/object.h', 'scene/geometry.h'):
        text = strip_comment(read(CYCLES, path))
        for found in re.finditer(r'\benum\s*(?::\s*\w+\s*)?\{(.*?)\}', text, flags=re.S):
            owner = re.findall(r'\bclass\s+(\w+)[^;{]*\{', text[:found.start()])
            owner = owner[-1] if owner else ''
            for item in found.group(1).split(','):
                name = item.partition('=')[0].strip()
                value = names.scoped.get((owner, name))
                if re.fullmatch(r'\w+', name) and value is not None:
                    rows.append((owner or '-', (owner + '::' if owner else '') + name, show(value & 0xFFFFFFFF)))
    return rows


def bvh_constant(names):
    """The BVH's types and limits, and the sizes of its nodes."""
    rows = []
    for path in ('bvh/params.h', 'bvh/binning.h'):
        text = strip_comment(read(CYCLES, path))
        for found in re.finditer(r'\benum\s*(\w*)\s*\{(.*?)\}', text, flags=re.S):
            owner = re.findall(r'\bclass\s+(\w+)[^;{]*\{', text[:found.start()])
            owner = found.group(1) or (owner[-1] if owner else '')
            for item in found.group(2).split(','):
                name = item.partition('=')[0].strip()
                value = names.scoped.get((owner, name))
                if re.fullmatch(r'\w+', name) and value is not None:
                    rows.append((owner, name if found.group(1) else owner + '::' + name, show(value)))
    for path in ('bvh/bvh.h', 'bvh/bvh2.h'):
        text = strip_comment(read(CYCLES, path))
        for name, given in re.findall(r'^#\s*define (\w+) ([^\n\\]+)$', text, flags=re.M):
            value = names.number(given)
            if value is not None:
                rows.append(('define', name, show(value)))
    return rows


def main():
    names = Names(CYCLES)
    # The kernel's own, then the few the scene's managers define for themselves.
    text = ''.join(strip_comment(read(CYCLES, path)) for path in ('kernel/types.h', 'kernel/svm/types.h', 'scene/tables.h', 'scene/film.h'))
    rows, missing = [], 0
    for found in re.finditer(r'\benum(?:\s+class)?\s*(\w*)\s*(?::\s*\w+\s*)?\{(.*?)\}', text, flags=re.S):
        for item in found.group(2).split(','):
            name = item.partition('=')[0].strip()
            if not re.fullmatch(r'\w+', name):
                continue
            value = names.scoped.get((found.group(1), name)) if found.group(1) else None
            value = names.lookup(name) if value is None else value
            missing += value is None
            if value is not None:
                rows.append((found.group(1) or '-', name, show(value)))
    rows.extend(socket_flag(names))
    rows.extend(manager_flag(names))
    # A define may stand on one before it (KERNEL_FEATURE_AO), so each one
    # worked out is known to those after it.
    text += strip_comment(read(CYCLES, 'kernel/features.h'))
    for name, given in re.findall(r'^#\s*define (\w+) ([^\n\\]+)$', text, flags=re.M):
        value = names.number(given)
        if value is not None:
            names.bare.setdefault(name, set()).add(value)
            rows.append(('define', name, show(value)))
    rows.extend(bvh_constant(names))
    head = [
        '# Generated by tool/constant.py from Cycles: kernel/types.h,',
        '# kernel/svm/types.h, kernel/features.h, scene/tables.h and scene/film.h,',
        '# SocketType::Flags of graph/node_type.h, the managers\' update flags of scene/object.h',
        '# and scene/geometry.h, and the BVH\'s types, limits and node sizes of',
        '# bvh/params.h, bvh/binning.h, bvh/bvh.h and bvh/bvh2.h. Do not edit by',
        '# hand. Every enumerator and every #define that stands for a number.',
        '#',
        '# enum, or "define", or "-" for an enum with no name	name	number',
    ]
    out = os.path.join(HERE, 'data', 'constant.tsv')
    with open(out, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(head + ['\t'.join(row) for row in rows]) + '\n')
    print(out, len(rows), 'rows;', missing, 'enumerators without a number')


main()
