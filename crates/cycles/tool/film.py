"""Write data/film.tsv from Cycles' own source, so no pass offset is typed in.

  python tool/film.py <path to intern/cycles>

Reads `Film::device_update` (scene/film.cpp): the members of the kernel's
film data it marks unused before laying the passes out, and the member each
pass type's offset is written to. And `Film::update_passes`: the names of
the passes it adds by itself.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from value import read, strip_comment  # noqa: E402

CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    text = strip_comment(read(CYCLES, 'scene/film.cpp'))
    body = re.search(r'void Film::device_update\(.*?\n\}\n', text, flags=re.S).group(0)
    rows = [('unused', '-', name, '-') for name in re.findall(r'kfilm->(\w+) = PASS_UNUSED;', body)]
    switch = re.search(r'switch \(pass->get_type\(\)\) \{(.*?)default:', body, flags=re.S).group(1)
    for name, case in re.findall(r'case (PASS_\w+):(.*?)break;', switch, flags=re.S):
        member = re.search(r'kfilm->(\w+) =', case).group(1)
        # Several passes of a type share one offset: the lowest for
        # cryptomatte, the first for the AOVs.
        rule = 'lowest' if 'min(' in case else ('first' if 'if (!have_' in case else 'set')
        rows.append(('offset', name, member, rule))
    # The names `Film::update_passes` gives the passes it adds by itself.
    for name, mode, label in re.findall(r'add_auto_pass\(scene, (PASS_\w+), (?:PassMode::(\w+), )?"([^"]+)"\)', text):
        rows.append(('name', name, (mode or 'NOISY').lower(), label))
    head = [
        '# Generated by tool/film.py from Cycles: Film::device_update in',
        '# scene/film.cpp. Do not edit by hand.',
        '#',
        '# unused	-	member of the film data marked PASS_UNUSED first	-',
        '# offset	pass type	member its offset is written to	set, or first, or lowest of several passes',
        '# name	pass type	noisy or denoised	the name of the pass the film adds by itself',
    ]
    out = os.path.join(HERE, 'data', 'film.tsv')
    with open(out, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(head + ['\t'.join(row) for row in rows]) + '\n')
    print(out, len(rows), 'rows')


main()
