"""Write data/pass.tsv from Cycles' own source, so the table is never typed in.

  python tool/pass.py <path to intern/cycles>

Reads the `PassType` enum (kernel/types.h) for names and numbers, and the
switch in `Pass::get_info` (scene/pass.cpp) for what each pass holds.
"""
import io
import os
import re
import sys

CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(rel):
    return io.open(os.path.join(CYCLES, rel), encoding='utf-8').read()


def enum_values(text):
    body = re.search(r'enum PassType \{(.*?)\n\};', text, flags=re.S).group(1)
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    value, out = -1, []
    for name, given in re.findall(r'(PASS_\w+)(?:\s*=\s*(\d+))?\s*,', body):
        value = int(given) if given else value + 1
        out.append((name, value))
    return out


def switch_bodies(text):
    start = text.index('PassInfo Pass::get_info(const PassType type')
    body = text[start:text.index('bool Pass::contains', start)]
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    out = {}
    for labels, code in re.findall(r'((?:\s*case PASS_\w+:)+)(.*?)break;', body, flags=re.S):
        for name in re.findall(r'case (PASS_\w+):', labels):
            out[name] = code
    return out


def row(name, value, code):
    info = dict(component='0', lightgroup='', denoised='', filter='1', exposure='0', written='1', divide='PASS_NONE',
                divide_rule='always', direct='PASS_NONE', indirect='PASS_NONE', compositing='0',
                denoising_albedo='1', denoise='no', scale='1')
    for field, expr in re.findall(r'pass_info\.(\w+)\s*=\s*(.*?);', code, flags=re.S):
        expr = ' '.join(expr.split())
        flag = {'true': '1', 'false': '0'}.get(expr)
        if field == 'num_components':
            both = re.match(r'is_lightgroup \? (\d+) : (\d+)', expr)
            mode = re.match(r'\(mode == PassMode::NOISY\) \? (\d+) : (\d+)', expr)
            if both:
                info['lightgroup'], info['component'] = both.group(1), both.group(2)
            elif mode:
                info['component'], info['denoised'] = mode.group(1), mode.group(2)
            else:
                info['component'] = expr
        elif field == 'divide_type':
            rule = re.match(r'\(!include_albedo\) \? (PASS_\w+) : PASS_NONE', expr)
            info['divide'], info['divide_rule'] = (rule.group(1), 'without_albedo') if rule else (expr, 'always')
        elif field == 'support_denoise':
            info['denoise'] = {'true': 'yes', '!is_lightgroup': 'not_lightgroup'}[expr]
        elif field == 'scale':
            info['scale'] = 'timer'
        else:
            key = {'use_filter': 'filter', 'use_exposure': 'exposure', 'is_written': 'written',
                   'direct_type': 'direct', 'indirect_type': 'indirect', 'use_compositing': 'compositing',
                   'use_denoising_albedo': 'denoising_albedo'}[field]
            info[key] = flag if flag is not None else expr
    order = ['component', 'lightgroup', 'denoised', 'filter', 'exposure', 'written', 'divide', 'divide_rule',
             'direct', 'indirect', 'compositing', 'denoising_albedo', 'denoise', 'scale']
    return '\t'.join([name, str(value)] + [info[key] or '-' for key in order])


values = enum_values(read('kernel/types.h'))
bodies = switch_bodies(read('scene/pass.cpp'))
lines = [
    '# Generated by tool/pass.py from Cycles: kernel/types.h (PassType) and',
    '# scene/pass.cpp (Pass::get_info). Do not edit by hand.',
    '#',
    '# name\tvalue\tcomponent\tlightgroup\tdenoised\tfilter\texposure\twritten\tdivide\tdivide_rule\tdirect\tindirect\tcompositing\tdenoising_albedo\tdenoise\tscale',
]
for name, value in values:
    lines.append(row(name, value, bodies[name]) if name in bodies else '%s\t%d\tmarker' % (name, value))
io.open(os.path.join(HERE, 'data', 'pass.tsv'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(len(values), 'names,', len(bodies), 'with a layout')
