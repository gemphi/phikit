"""Write data/state.tsv from Cycles' own source, so no field is typed in.
  python tool/state.py <path to intern/cycles>
Reads the path state's templates, `kernel/integrator/state_template.h` and
`shadow_state_template.h`: for each struct, its members in order, each with
its C++ type, its array size (the volume stack's, else 1) and the kernel
feature that turns it on. The state of a path in `kernel/integrator/state.rs`
is checked against this table, field by field.
"""
import os
import re
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from value import read, strip_comment  # noqa: E402
CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(os.path.dirname(__file__)))
FILE = [('state', 'kernel/integrator/state_template.h'), ('shadow', 'kernel/integrator/shadow_state_template.h')]
BEGIN = re.compile(r'KERNEL_STRUCT_BEGIN(?:_PACKED)?\((\w+)')
MEMBER = re.compile(r'KERNEL_STRUCT_(?:ARRAY_)?MEMBER(?:_PACKED)?\(\s*(\w+),\s*([\w:* ]+?),\s*(\w+),\s*(\w+)\s*\)')
def rows():
    out = []
    for kind, path in FILE:
        text = strip_comment(read(CYCLES, path))
        # `#if defined(__PATH_GUIDING__)` picks the pointer type; the plain
        # branch (`uint64_t`) is the one the device sees.
        text = re.sub(r'#if defined\(__PATH_GUIDING__\)(.*?)#else(.*?)#endif', r'\2', text, flags=re.S)
        for member in MEMBER.finditer(text):
            struct, ctype, name, feature = member.groups()
            packed = 'PACKED' in member.group(0).split('(')[0]
            array = 'ARRAY' in member.group(0).split('(')[0]
            out.append((kind, struct, name, ctype, '1' if packed else '0', '1' if array else '0', feature))
    return out
def main():
    row = rows()
    head = [
        '# Generated by tool/state.py from Cycles: kernel/integrator/state_template.h',
        '# and shadow_state_template.h. Do not edit by hand.',
        '# The members of the path state and of the shadow path state, in order.',
        '#',
        '# template	struct	name	C++ type	packed	array	feature',
    ]
    out = os.path.join(HERE, 'data', 'state.tsv')
    with open(out, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(head + ['\t'.join(item) for item in row]) + '\n')
    print(out, len(row), 'rows')
main()
