"""Write data/sobol.tsv from Cycles' own source, so no number is typed in.
  python tool/sobol.py <path to intern/cycles>
Reads `sobol_burley_table` (kernel/tables.h): the four Sobol direction
vectors, 32 numbers each, bit-reversed, that `sobol_burley` (kernel/sample/
sobol_burley.h) XORs together. One row for each dimension.
"""
import os
import re
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from value import read, strip_comment  # noqa: E402
CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def main():
    text = strip_comment(read(CYCLES, 'kernel/tables.h'))
    body = re.search(r'sobol_burley_table\[4\]\[32\] = \{(.*?)\n\};', text, flags=re.S).group(1)
    rows = []
    for block in re.findall(r'\{([^{}]*)\}', body):
        number = re.findall(r'0x[0-9a-fA-F]+', block)
        assert len(number) == 32, len(number)
        rows.append(number)
    assert len(rows) == 4, len(rows)
    head = [
        '# Generated by tool/sobol.py from Cycles: sobol_burley_table of',
        '# kernel/tables.h. Do not edit by hand.',
        '# The direction numbers of a dimension, 32 of them, bit-reversed.',
        '#',
        '# dimension	number x 32',
    ]
    out = os.path.join(HERE, 'data', 'sobol.tsv')
    with open(out, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(head + [str(index) + '\t' + '\t'.join(row) for index, row in enumerate(rows)]) + '\n')
    print(out, len(rows), 'rows')
main()
