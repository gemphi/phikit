"""Write data/param.tsv from Cycles' own source, so no default is typed in.

  python tool/param.py <path to intern/cycles>

Reads the constructors of `BVHParams` (bvh/params.h) and `SceneParams`
(scene/scene.h): what each member starts as, as a number. A member given
its value where it is declared is read there. A member with no number to
start as, such as a path, has no row.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from value import Names, read, show, strip_comment  # noqa: E402

CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OWNER = [('BVHParams', 'bvh/params.h'), ('SceneParams', 'scene/scene.h')]


def default_list(names, owner, path):
    """(owner, member, number) for each member the class gives a first value."""
    text = strip_comment(read(CYCLES, path))
    text = text[text.index('class ' + owner):]
    made = re.search(r'\b' + owner + r'\(\)\s*\{(.*?)\n  \}', text, flags=re.S)
    given = re.findall(r'^\s*(?:bool|int|float) (\w+) = ([^;]+);', text[:made.start()], flags=re.M)
    given += re.findall(r'^\s*(\w+) = ([^;]+);', made.group(1), flags=re.M)
    rows = []
    for name, value in given:
        number = names.number(value)
        if number is None:
            raise SystemExit('%s::%s starts as %s, which is not a number' % (owner, name, value))
        rows.append((owner, name, show(number)))
    return rows


def main():
    names = Names(CYCLES)
    rows = [row for owner, path in OWNER for row in default_list(names, owner, path)]
    head = [
        '# Generated by tool/param.py from Cycles: the constructors of BVHParams',
        '# (bvh/params.h) and SceneParams (scene/scene.h). Do not edit by hand.',
        '# What each member starts as; true is 1, and an enumerator is its number.',
        '#',
        '# class	member	number',
    ]
    out = os.path.join(HERE, 'data', 'param.tsv')
    with open(out, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(head + ['\t'.join(row) for row in rows]) + '\n')
    print(out, len(rows), 'rows')


main()
