"""Write data/svm.tsv from Cycles' own source, so no number is typed in.
  python tool/svm.py <path to intern/cycles>
Reads `kernel/svm/node_types_template.h`: the shader node types in the
order of `ShaderNodeType` (kernel/svm/types.h), where a `_DERIVATIVE`
type takes the number after its plain one. The stream of words the SVM
runs begins each node with its number.
"""
import os
import re
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from value import read, strip_comment  # noqa: E402
CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def main():
    text = strip_comment(read(CYCLES, 'kernel/svm/node_types_template.h'))
    row = []
    for kind, name in re.findall(r'^SHADER_NODE_TYPE(_DERIVATIVE)?\((\w+)\)', text, flags=re.M):
        row.append(name)
        if kind:
            row.append(name + '_DERIVATIVE')
    head = [
        '# Generated by tool/svm.py from Cycles: kernel/svm/node_types_template.h.',
        '# Do not edit by hand. ShaderNodeType, by number.',
        '#',
        '# node	number',
    ]
    out = os.path.join(HERE, 'data', 'svm.tsv')
    with open(out, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(head + [name + '\t' + str(number) for number, name in enumerate(row)]) + '\n')
    print(out, len(row), 'rows')
main()
