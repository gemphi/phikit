"""Write data/attribute.tsv from Cycles' own source, so no attribute is typed in.

  python tool/attribute.py <path to intern/cycles>

Reads scene/attribute.cpp: the name of each standard attribute
(`Attribute::standard_name`), and for each kind of geometry the type and
the element a standard attribute has on it (`find_type_from_geometry_std`,
`find_element_from_geometry_std`).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from value import read, strip_comment  # noqa: E402

CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def body_of(text, head):
    """The body of the function whose first line has `head`."""
    start = text.index(head)
    return text[text.index('{', start):text.index('\n}', start)]


def case_list(body):
    """(labels, what is returned) for each run of `case` labels that ends in a return."""
    out, label = [], []
    for line in body.splitlines():
        found = re.match(r'\s*case (\w+):', line)
        if found:
            label.append(found.group(1))
            continue
        found = re.match(r'\s*return ([^;]+);', line)
        if found and label:
            out.append((label, found.group(1).strip()))
        if found or 'break;' in line or re.match(r'\s*default:', line):
            label = []
    return out


def by_geometry(text, head, row):
    part = re.split(r'if \(geometry->is_(\w+)\(\)\)', body_of(text, head))
    out = []
    for geometry, body in zip(part[1::2], part[2::2]):
        for label, given in case_list(body):
            out.extend((row, geometry, name, given) for name in label)
    return out


def main():
    text = strip_comment(read(CYCLES, 'scene/attribute.cpp'))
    rows = []
    for label, given in case_list(body_of(text, 'Attribute::standard_name(AttributeStandard std)')):
        name = given.strip('"')
        rows.extend(('name', item, name) for item in label if name)
    rows.extend(by_geometry(text, 'find_type_from_geometry_std(Geometry *geometry', 'type'))
    rows.extend(by_geometry(text, 'find_element_from_geometry_std(Geometry *geometry', 'element'))
    head = [
        '# Generated by tool/attribute.py from Cycles: scene/attribute.cpp. Do not',
        '# edit by hand. The standard attributes: their names, and the type and',
        '# the element each has on a kind of geometry.',
        '#',
        '# name	standard	name',
        '# type	geometry	standard	type',
        '# element	geometry	standard	element',
    ]
    out = os.path.join(HERE, 'data', 'attribute.tsv')
    with open(out, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(head + ['\t'.join(row) for row in rows]) + '\n')
    print(out, len(rows), 'rows')


main()
