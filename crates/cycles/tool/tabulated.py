"""Write data/tabulated.tsv from Cycles' own source, so no number is typed in.
  python tool/tabulated.py <path to intern/cycles>
Reads `xors` of `tabulated_sobol_generate_4D` (scene/tabulated_sobol.cpp):
for each of the four dimensions, the 32 values that permute the order in
which the strata are visited, which is what makes the points an
Owen-scrambled Sobol sequence (Helmer, Christensen and Kensler,
"Stochastic Generation of (t, s) Sample Sequences").
"""
import os
import re
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from value import read, strip_comment  # noqa: E402
CYCLES = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def main():
    text = strip_comment(read(CYCLES, 'scene/tabulated_sobol.cpp'))
    body = re.search(r'xors\[4\]\[32\] = \{(.*?)\n  \};', text, flags=re.S).group(1)
    rows = []
    for block in re.findall(r'\{([^{}]*)\}', body):
        number = re.findall(r'0x[0-9a-fA-F]+|\b\d+\b', block)
        assert len(number) == 32, len(number)
        rows.append([str(int(value, 0)) for value in number])
    assert len(rows) == 4, len(rows)
    head = [
        '# Generated by tool/tabulated.py from Cycles: the xors of',
        '# tabulated_sobol_generate_4D (scene/tabulated_sobol.cpp). Do not edit by hand.',
        '# For each dimension, the 32 values that permute the order of the strata.',
        '#',
        '# dimension	xor x 32',
    ]
    out = os.path.join(HERE, 'data', 'tabulated.tsv')
    with open(out, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(head + [str(index) + '\t' + '\t'.join(row) for index, row in enumerate(rows)]) + '\n')
    print(out, len(rows), 'rows')
main()
