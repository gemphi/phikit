"""Bake DejaVu Sans glyph outlines into a Rust table.

Blender's Text object is a font curve: the glyph's outline is the curve,
and `extrude` gives it depth. Reading a TTF at run time would mean a font
parser and a hinting-free rasteriser in the crate; baking one font's
outlines is the same geometry with none of that, and it is the geometry
that the mesh wants.
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import RecordingPen

PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
CHARS = [chr(c) for c in range(32, 127)]
TOL = 0.012  # em; flattening tolerance

font = TTFont(PATH)
upem = font["head"].unitsPerEm
cmap = font.getBestCmap()
gs = font.getGlyphSet()
hmtx = font["hmtx"]

def quad(p0, p1, p2, n):
    return [((1-t)**2*p0[0]+2*(1-t)*t*p1[0]+t*t*p2[0], (1-t)**2*p0[1]+2*(1-t)*t*p1[1]+t*t*p2[1])
            for t in [i/n for i in range(1, n+1)]]

def cube(p0, p1, p2, p3, n):
    out=[]
    for i in range(1, n+1):
        t=i/n; m=1-t
        out.append((m**3*p0[0]+3*m*m*t*p1[0]+3*m*t*t*p2[0]+t**3*p3[0],
                    m**3*p0[1]+3*m*m*t*p1[1]+3*m*t*t*p2[1]+t**3*p3[1]))
    return out

def steps(pts):
    # crude: longer control polygon -> more steps
    d = sum(((pts[i+1][0]-pts[i][0])**2+(pts[i+1][1]-pts[i][1])**2)**0.5 for i in range(len(pts)-1))
    return max(2, min(16, int((d/upem)/TOL)))

out_glyphs = []
for ch in CHARS:
    name = cmap.get(ord(ch))
    adv = 0.0
    contours = []
    if name is not None:
        adv = hmtx[name][0] / upem
        pen = RecordingPen()
        gs[name].draw(pen)
        cur = []
        start = None
        for op, args in pen.value:
            if op == "moveTo":
                if len(cur) >= 3: contours.append(cur)
                start = args[0]; cur = [start]
            elif op == "lineTo":
                cur.append(args[0])
            elif op == "qCurveTo":
                pts = list(args)
                # fontTools gives (c1, c2, ..., end); end may be None (implied)
                if pts[-1] is None:
                    pts = pts[:-1]
                    # implied on-curve midpoints
                    p = cur[-1]
                    for i in range(len(pts)):
                        c = pts[i]
                        nxt = pts[(i+1) % len(pts)]
                        mid = ((c[0]+nxt[0])/2, (c[1]+nxt[1])/2)
                        cur.extend(quad(p, c, mid, steps([p, c, mid]))); p = mid
                else:
                    p = cur[-1]
                    for i in range(len(pts)-1):
                        c = pts[i]
                        nxt = pts[i+1] if i+1 == len(pts)-1 else ((pts[i][0]+pts[i+1][0])/2, (pts[i][1]+pts[i+1][1])/2)
                        cur.extend(quad(p, c, nxt, steps([p, c, nxt]))); p = nxt
            elif op == "curveTo":
                p = cur[-1]; a, b, c = args
                cur.extend(cube(p, a, b, c, steps([p, a, b, c])))
            elif op == "closePath":
                if len(cur) >= 3: contours.append(cur)
                cur = []
        if len(cur) >= 3: contours.append(cur)
    # normalise to em, drop a duplicated last point
    norm = []
    for c in contours:
        pts = [(round(x/upem, 5), round(y/upem, 5)) for x, y in c]
        if len(pts) > 1 and abs(pts[0][0]-pts[-1][0]) < 1e-6 and abs(pts[0][1]-pts[-1][1]) < 1e-6:
            pts = pts[:-1]
        if len(pts) >= 3:
            norm.append(pts)
    out_glyphs.append((ch, adv, norm))

total = sum(len(c) for _, _, cs in out_glyphs for c in cs)
print("glyphs", len(out_glyphs), "points", total, file=sys.stderr)

lines = []
lines.append("#![allow(clippy::approx_constant)]")
lines.append("//! (A baked coordinate that lands near 2/pi or log10(e) is a coordinate,")
lines.append("//! not a constant anyone meant to write.)")
lines.append("//! DejaVu Sans glyph outlines, baked.")
lines.append("//!")
lines.append("//! Blender's Text object is a **font curve**: the glyph's outline is the")
lines.append("//! curve and `Curve.ext1` (Geometry ▸ Extrude) gives it depth. Reading a")
lines.append("//! TTF at run time would mean a font parser in the crate; baking one")
lines.append("//! font's outlines is the same geometry with none of that, and the")
lines.append("//! geometry is what the mesh wants. Generated by `tooling/bake_font.py`")
lines.append("//! from DejaVuSans.ttf (Bitstream Vera / DejaVu licence) at a flattening")
lines.append("//! tolerance of 0.012 em, in em units with the baseline at y = 0.")
lines.append("")
lines.append("/// One glyph: its advance width in em, and its contours.")
lines.append("pub struct Glyph {")
lines.append("    pub advance: f32,")
lines.append("    pub contour: &'static [&'static [(f32, f32)]],")
lines.append("}")
lines.append("")
lines.append("/// ASCII 32..=126, in order.")
lines.append("pub const FIRST: u8 = 32;")
lines.append("")
for ch, adv, cs in out_glyphs:
    tag = f"G{ord(ch)}"
    for k, c in enumerate(cs):
        body = ", ".join(f"({x:.5}, {y:.5})" for x, y in c)
        lines.append(f"const {tag}_{k}: &[(f32, f32)] = &[{body}];")
    if cs:
        lines.append(f"const {tag}: &[&[(f32, f32)]] = &[{', '.join(f'{tag}_{k}' for k in range(len(cs)))}];")
    else:
        lines.append(f"const {tag}: &[&[(f32, f32)]] = &[];")
lines.append("")
lines.append("pub static GLYPH: &[Glyph] = &[")
for ch, adv, cs in out_glyphs:
    lines.append(f"    Glyph {{ advance: {adv:.5}, contour: G{ord(ch)} }},")
lines.append("];")
lines.append("")
print("\n".join(lines))
